// Bundles drizzle/ into src/migrations.generated.ts so migrate() and the schema
// check run without a filesystem (Workers, bundled serverless functions).
// Split and hash exactly as drizzle's readMigrationFiles does, so databases the
// drizzle file migrator migrated keep matching bookkeeping.
//
//   node scripts/bundle-migrations.mjs          write the file
//   node scripts/bundle-migrations.mjs --check  exit 1 if the file is stale
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const drizzleDir = new URL('../drizzle/', import.meta.url);
const outFile = new URL('../src/migrations.generated.ts', import.meta.url);

const journal = JSON.parse(readFileSync(new URL('meta/_journal.json', drizzleDir), 'utf8'));
const migrations = journal.entries.map(({ tag, when }) => {
  const sql = readFileSync(new URL(`${tag}.sql`, drizzleDir), 'utf8');
  return {
    tag,
    when,
    hash: createHash('sha256').update(sql).digest('hex'),
    statements: sql.split('--> statement-breakpoint'),
  };
});

const source = `// Generated by scripts/bundle-migrations.mjs from drizzle/. Do not edit;
// run \`pnpm --filter @plandesk/db generate\` after adding a migration.
export const MIGRATIONS: readonly {
  tag: string;
  when: number;
  hash: string;
  statements: string[];
}[] = ${JSON.stringify(migrations, null, 2)};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(outFile, 'utf8') !== source) {
    console.error(
      'src/migrations.generated.ts is stale: run `pnpm --filter @plandesk/db generate`',
    );
    process.exit(1);
  }
} else {
  writeFileSync(outFile, source);
}
